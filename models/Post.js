const mongoose = require('mongoose');

// =====================================================
// POST SCHEMA
// =====================================================

const postSchema = new mongoose.Schema(
  {
    title: {
      type: String,
      required: true,
      trim: true,
    },

    content: {
      type: String,
      required: true,
      trim: true,
    },

    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
  },
  {
    timestamps: true,
  }
);

// =====================================================
// CREATE AND EXPORT MODEL
// =====================================================

const Post = mongoose.model('Post', postSchema);

module.exports = Post;
